import { slugifyTitle } from './chartFormatters';

/**
 * Exports a chart card as a crisp, high-resolution PNG image.
 * Uses pure HTML5 Canvas & SVG XMLSerializer (no external heavy libraries needed).
 * 
 * @param {HTMLElement} containerElement - DOM node containing the chart card
 * @param {string} title - Chart title to render and use as filename
 * @param {string} subtitle - Optional description to include in the exported card
 */
export const exportChartAsPNG = async (containerElement, title = 'academic-chart', subtitle = '') => {
  if (!containerElement) {
    throw new Error('Chart container element not found.');
  }

  // 1. Find the SVG element generated by Recharts
  const svgElement = containerElement.querySelector('svg.recharts-surface') || containerElement.querySelector('svg');
  if (!svgElement) {
    throw new Error('SVG chart surface not found within container.');
  }

  const svgRect = svgElement.getBoundingClientRect();
  const width = Math.max(svgRect.width || 600, 500);
  const height = Math.max(svgRect.height || 360, 300);

  // Padding & header margins for exported card
  const paddingX = 32;
  const paddingTop = title ? 64 : 24;
  const paddingBottom = 32;
  const cardWidth = width + paddingX * 2;
  const cardHeight = height + paddingTop + paddingBottom;

  // 2. Clone the SVG and inline all computed styles
  const clonedSvg = svgElement.cloneNode(true);
  clonedSvg.setAttribute('width', width);
  clonedSvg.setAttribute('height', height);

  // Recursively copy computed styles from original SVG elements to cloned elements
  const copyComputedStyles = (source, target) => {
    const computed = window.getComputedStyle(source);
    // Explicitly inline essential SVG attributes
    const fill = computed.getPropertyValue('fill');
    const stroke = computed.getPropertyValue('stroke');
    const strokeWidth = computed.getPropertyValue('stroke-width');
    const font = computed.getPropertyValue('font-family');
    const fontSize = computed.getPropertyValue('font-size');
    const fontWeight = computed.getPropertyValue('font-weight');

    if (fill && fill !== 'none') target.style.fill = fill;
    if (stroke && stroke !== 'none') target.style.stroke = stroke;
    if (strokeWidth) target.style.strokeWidth = strokeWidth;
    if (font) target.style.fontFamily = font;
    if (fontSize) target.style.fontSize = fontSize;
    if (fontWeight) target.style.fontWeight = fontWeight;

    for (let i = 0; i < source.children.length; i++) {
      if (target.children[i]) {
        copyComputedStyles(source.children[i], target.children[i]);
      }
    }
  };
  copyComputedStyles(svgElement, clonedSvg);

  // 3. Serialize SVG to data URL
  const serializer = new XMLSerializer();
  const svgString = serializer.serializeToString(clonedSvg);
  const svgBlob = new Blob([svgString], { type: 'image/svg+xml;charset=utf-8' });
  const svgUrl = URL.createObjectURL(svgBlob);

  // 4. Create high-resolution 2x Canvas
  const scale = 2; // Retina 2x scale
  const canvas = document.createElement('canvas');
  canvas.width = cardWidth * scale;
  canvas.height = cardHeight * scale;
  const ctx = canvas.getContext('2d');
  ctx.scale(scale, scale);

  // 5. Draw Card Background
  ctx.fillStyle = '#ffffff';
  ctx.fillRect(0, 0, cardWidth, cardHeight);

  // Card Border (subtle)
  ctx.strokeStyle = '#e2e8f0';
  ctx.lineWidth = 1;
  ctx.strokeRect(0, 0, cardWidth, cardHeight);

  // 6. Draw Header (Title & Subtitle)
  if (title) {
    ctx.font = '600 16px Inter, system-ui, -apple-system, sans-serif';
    ctx.fillStyle = '#0f172a';
    ctx.fillText(title, paddingX, 36);

    if (subtitle) {
      ctx.font = '400 12px Inter, system-ui, -apple-system, sans-serif';
      ctx.fillStyle = '#64748b';
      ctx.fillText(subtitle, paddingX, 54);
    }
  }

  // 7. Load and Draw SVG onto Canvas
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.crossOrigin = 'anonymous';

    img.onload = () => {
      ctx.drawImage(img, paddingX, paddingTop, width, height);
      URL.revokeObjectURL(svgUrl);

      // 8. Convert to PNG & Trigger Download
      try {
        canvas.toBlob((blob) => {
          if (!blob) {
            reject(new Error('Canvas to Blob conversion failed.'));
            return;
          }
          const downloadUrl = URL.createObjectURL(blob);
          const link = document.createElement('a');
          const cleanFilename = `${slugifyTitle(title)}.png`;
          link.href = downloadUrl;
          link.download = cleanFilename;
          document.body.appendChild(link);
          link.click();
          document.body.removeChild(link);
          URL.revokeObjectURL(downloadUrl);
          resolve(cleanFilename);
        }, 'image/png');
      } catch (err) {
        reject(err);
      }
    };

    img.onerror = (err) => {
      URL.revokeObjectURL(svgUrl);
      reject(new Error(`Failed to render SVG image onto canvas: ${err}`));
    };

    img.src = svgUrl;
  });
};

export default exportChartAsPNG;
